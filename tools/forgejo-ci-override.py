#!/usr/bin/env -S python3 -I
"""Flatten gamespice-platform/ci validate.yml into a standalone workflow for the internal Forgejo.

Forgejo cannot expand that reusable workflow (workflow_call with a `secrets` key is rejected), so the mirror
commits this file as .forgejo/workflows/ci.yml on the Forgejo copy of each caller (never on GitHub).
Fast checks only: the Godot runtime steps are dropped (the shared VM runs suites through heavy/hv, not CI).
usage: forgejo-ci-override.py VALIDATE_YML CALLER_YML [BASE_URL]   -> workflow yaml on stdout, exit 3 when the
caller does not call validate.yml."""
import re, sys, yaml

if sys.argv[1] == "--plain":
    # A repo workflow that is not a validate.yml caller: same workflow with the setup-python steps dropped (the
    # host runner has no toolcache for the pinned version; its own python3 runs the checks). exit 3 when nothing
    # to change, so the repo is left alone.
    wf = yaml.safe_load(open(sys.argv[2]))
    hit = False
    for j in (wf.get("jobs") or {}).values():
        keep = [s for s in j.get("steps") or [] if "actions/setup-python" not in str(s.get("uses", ""))]
        hit = hit or len(keep) != len(j.get("steps") or [])
        if "steps" in j: j["steps"] = keep
    if not hit: sys.exit(3)
    print("# Generated by tools/forgejo-ci-override.py on the internal Forgejo copy only (docs/forgejo-ci.md).\n" + yaml.safe_dump(wf, sort_keys=False, width=10**6), end="")
    sys.exit(0)
vpath, cpath = sys.argv[1], sys.argv[2]
base = sys.argv[3] if len(sys.argv) > 3 else "http://127.0.0.1:3300"
val = yaml.safe_load(open(vpath))
call = yaml.safe_load(open(cpath))
withs = None
for j in (call.get("jobs") or {}).values():
    if re.match(r"gamespice-platform/ci/\.github/workflows/validate\.yml@", str(j.get("uses", ""))):
        withs = j.get("with") or {}
        break
if withs is None:
    sys.exit(3)
decl = val[True if True in val else "on"]["workflow_call"]["inputs"]
inp = {k: withs.get(k, v.get("default")) for k, v in decl.items()}
inp["godot"] = False  # fast checks only on the internal runner

def lit(v):
    if isinstance(v, bool): return "true" if v else "false"
    if v is None: return "''"
    if isinstance(v, (int, float)): return str(v)
    return "'" + str(v).replace("'", "''") + "'"

def sub(s):
    s = s.replace("secrets.DEPS_TOKEN || github.token", "github.token")
    s = s.replace("github.job_workflow_sha", "'main'")
    s = re.sub(r"inputs\.([a-z-]+)", lambda m: lit(inp[m.group(1)]), s)
    return s

def walk(o):
    if isinstance(o, str): return sub(o)
    if isinstance(o, dict): return {k: walk(v) for k, v in o.items()}
    if isinstance(o, list): return [walk(v) for v in o]
    return o

steps = []
for st in val["jobs"]["validate"]["steps"]:
    cond = str(st.get("if", ""))
    if "inputs.godot" in cond or "inputs.profiles" in cond or "inputs.perf" in cond:
        continue
    if "actions/cache" in str(st.get("uses", "")) or "apt-get" in str(st.get("run", "")):
        continue
    st = walk(st)
    m = re.fullmatch(r"\$\{\{ !(true|false) \}\}", str(st.get("continue-on-error", "")))
    if m:
        st["continue-on-error"] = m.group(1) == "false"
    if "if" in st:
        # `if: false` / `if: ''!=''` style leftovers: evaluate the constant forms, keep real expressions
        st["if"] = str(st["if"])
    if st.get("name", "").startswith("Check out the CI scripts"):
        st["with"] = {"repository": "gamespice-platform/ci", "ref": "main", "path": "dot-ci"}
    steps.append(st)

out = {"name": "ci", "on": {"push": {"branches": ["**"], "paths-ignore": ["**/*.md", "screenshots/**"]}, "workflow_dispatch": None},
       "jobs": {"validate": {"runs-on": "ubuntu-latest", "timeout-minutes": 30, "steps": steps}}}
text = yaml.safe_dump(out, sort_keys=False, width=10**6)
print("# Generated by tools/forgejo-ci-override.py on the internal Forgejo copy only (docs/forgejo-ci.md).\n" + text, end="")
